"""Добыча после победы в бою.

Удача даёт шанс найти что-то полезное сверх сюжетных предметов, которые
выдаёт Мастер Игры. Набор находок зависит от жанра — так «добыча» feels
уместной: в фэнтези это самоцветы и травы, в детективе — улики и записки.

Бросок делается обычным ``random``: добыча не влияет на формулы боя, поэтому
тесты формул от неё не зависят. Характеристика без «удачи» (заглушки в тестах)
даёт нулевой шанс — находка просто не выпадает.
"""

import random

from app.content import genres
from app.services import progression

# Что можно найти в каждом жанре. Ключи совпадают с кодами жанров.
LOOT_TABLE = {
    "fantasy": ["Горсть монет", "Самоцвет", "Лечебные травы", "Старый оберег"],
    "romance": ["Письмо", "Шёлковая лента", "Засушенный цветок", "Медальон"],
    "mystery": ["Улика", "Старая газета", "Обрывок записки", "Ключ"],
    "horror": ["Огарок свечи", "Спички", "Странный амулет", "Пожелтевшая страница"],
    "scifi": ["Микросхема", "Энергоячейка", "Чип данных", "Обломок дрона"],
    "historical": ["Старинные монеты", "Печать", "Письмо", "Медальон"],
    "adventure": ["Моток верёвки", "Компас", "Потёртая карта", "Горсть монет"],
    "universal": ["Горсть монет", "Припасы", "Небольшой трофей"],
}


def loot_for(genre_code: str) -> list:
    """Набор возможных находок для жанра."""
    code = genres.normalize(genre_code)
    return LOOT_TABLE.get(code, LOOT_TABLE["universal"])


def roll(player, rng=None) -> str:
    """Возвращает название найденного предмета или пустую строку.

    ``rng`` можно подменить (например, ``random.Random(seed)``) для тестов.
    """
    chance = progression.loot_chance(player)
    if chance <= 0:
        return ""

    rng = rng or random
    if rng.random() >= chance:
        return ""

    code = getattr(player, "genre", "") or genres.DEFAULT_GENRE
    return rng.choice(loot_for(code))
