_DASH_SPLIT = re.compile(r"\s+[—–-]\s+")


def split_note(text: str) -> tuple:
    """Делит «Название — описание» или «Название (описание)».

    Возвращает (название, описание). Если описания нет — второй элемент пустой.
    """
    text = (text or "").strip()
    if not text:
        return "", ""

    parenthetical = re.search(r"\s*\(([^()]*)\)\s*$", text)
    if parenthetical:
        name = text[: parenthetical.start()].strip()
        return name, parenthetical.group(1).strip()

    dash = _DASH_SPLIT.search(text)
    if dash:
        name = text[: dash.start()].strip()
        description = text[dash.end():].strip()
        return name, description

    return text, ""


def _category_text(name: str) -> str:
    lowered = (name or "").lower()
    for keywords, description in _CATEGORY_RULES:
        if any(word in lowered for word in keywords):
            return description
    return "Предмет из ваших странствий: пригодится, если знать, когда пустить его в дело."


